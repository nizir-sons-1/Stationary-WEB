  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  paper_type TEXT NOT NULL,
  brand_name TEXT NOT NULL,
  gsm TEXT NOT NULL DEFAULT '',
  rate_per_unit NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
  lengths TEXT DEFAULT '',
  widths TEXT DEFAULT '',
  is_active BOOLEAN NOT NULL DEFAULT true,
  last_updated TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  CONSTRAINT unique_paper_brand UNIQUE (paper_type, brand_name)
);

