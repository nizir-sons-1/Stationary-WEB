-- Policy 2: Authenticated staff / owner can manage (insert/update/delete) calculator rates
DROP POLICY IF EXISTS "Authenticated users can manage calculator rates" ON public.calculator_rates;
CREATE POLICY "Authenticated users can manage calculator rates"
  ON public.calculator_rates
  FOR ALL
  TO authenticated
  USING (true)
  WITH CHECK (true);

-- Auto-update last_updated trigger
CREATE OR REPLACE FUNCTION public.handle_calculator_rates_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.last_updated = timezone('utc'::text, now());
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS on_calculator_rates_updated ON public.calculator_rates;
CREATE TRIGGER on_calculator_rates_updated
  BEFORE UPDATE ON public.calculator_rates
  FOR EACH ROW
  EXECUTE FUNCTION public.handle_calculator_rates_updated_at();

